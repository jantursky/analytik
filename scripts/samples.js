// Copies the code blocks marked `ts sample` or `tsx sample` in the READMEs into apps/example/src/typecheck/,
// so `bun run typecheck` compiles them against the real library. `--check` fails when the copies are stale.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const sources = ['README.md', 'packages/analytik/README.md']
const outDir = join(root, 'apps/example/src/typecheck')
const check = process.argv.includes('--check')

const files = new Map()
for (const source of sources) {
  const text = readFileSync(join(root, source), 'utf8')
  const stem = source
    .replace(/\.md$/, '')
    .replace(/[^a-z0-9]+/gi, '-')
    .toLowerCase()
  let index = 0
  for (const match of text.matchAll(/```(tsx?) sample\n([\s\S]*?)```/g)) {
    index += 1
    const name = `${stem}-${index}.${match[1] === 'tsx' ? 'tsx' : 'ts'}`
    files.set(name, `// Generated by scripts/samples.js from ${source}. Do not edit.\n${match[2]}`)
  }
}

if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true })
const existing = readdirSync(outDir).filter((name) => name !== '.gitkeep')
const stale = existing.filter((name) => !files.has(name))
const changed = [...files].filter(
  ([name, body]) => !existing.includes(name) || readFileSync(join(outDir, name), 'utf8') !== body,
)

if (check) {
  if (stale.length || changed.length) {
    console.error('Doc samples are out of date. Run `bun run sync:samples`.')
    process.exit(1)
  }
} else {
  for (const name of stale) rmSync(join(outDir, name))
  for (const [name, body] of changed) writeFileSync(join(outDir, name), body)
  console.log(`${files.size} samples synced`)
}
