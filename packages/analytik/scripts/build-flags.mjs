// Builds src/dashboard/flags-data.ts from the Circle Flags set (HatScripts, MIT): every ISO 3166 country as the inner
// markup of its SVG, so the dashboard loads them as one lazy chunk. Run `bun run build:flags` after updating
// `circle-flags`; the result is committed.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const flags = join(root, 'node_modules/circle-flags/flags')

const entries = {}
for (const file of readdirSync(flags)
  .filter((name) => /^[a-z]{2}\.svg$/.test(name))
  .sort()) {
  const code = file.slice(0, 2).toUpperCase()
  const svg = readFileSync(join(flags, file), 'utf8').trim()
  const inner = svg.match(/^<svg[^>]*>(.*)<\/svg>$/s)?.[1]
  if (!inner) throw new Error(`Unexpected markup in ${file}`)
  // The same flag can appear many times in one page, so each mask id is made unique per country.
  entries[code] = inner
    .replaceAll('id="a"', `id="analytik-flag-${code}"`)
    .replaceAll('url(#a)', `url(#analytik-flag-${code})`)
}

const lines = Object.entries(entries).map(([code, markup]) => `  ${code}: ${JSON.stringify(markup)},`)
writeFileSync(
  join(root, 'src/dashboard/flags-data.ts'),
  `// Generated by scripts/build-flags.mjs from circle-flags (MIT, HatScripts); do not edit.\n` +
    `/** Inner SVG markup (viewBox 0 0 512 512) per ISO 3166 country code. */\n` +
    `export default {\n${lines.join('\n')}\n} as Record<string, string>\n`,
)
console.log(`${lines.length} flags`)
